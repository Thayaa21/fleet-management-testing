"""Shipments, state machine, milestones (append-only + void), audit, and the
stale_for_hours data-gap filter."""
from datetime import datetime, timedelta, timezone

import pytest


@pytest.fixture()
def staff(client, token_for):
    return {"Authorization": f"Bearer {token_for('admin')}"}


@pytest.fixture()
def shipment(client, staff):
    r = client.post("/shipments", headers=staff, json={"bol_number": "BOL1"})
    assert r.status_code == 201, r.text
    return r.json()


def _iso(dt):
    return dt.astimezone(timezone.utc).isoformat()


def _add(client, staff, sid, code, event_at=None, source="manual"):
    body = {"event_code": code, "source": source}
    if event_at is not None:
        body["event_at"] = _iso(event_at)
    return client.post(f"/shipments/{sid}/milestones", headers=staff, json=body)


