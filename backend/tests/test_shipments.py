# ── Audit rows ──
def test_audit_rows_created_for_shipment_and_milestone(client, staff, shipment):
    sid = shipment["id"]
    _add(client, staff, sid, "PICKED_UP")
    audit = client.get(f"/audit?entity_type=shipments&entity_id={sid}", headers=staff).json()
    actions = {a["action"] for a in audit["items"]}
    assert "create" in actions  # shipment creation audited
    # Milestone create is audited too.
    m_audit = client.get("/audit?entity_type=milestones", headers=staff).json()
    assert m_audit["total"] >= 1


def test_cancel_is_audited_and_no_hard_delete(client, staff, shipment):
    sid = shipment["id"]
    resp = client.post(f"/shipments/{sid}/cancel", headers=staff, json={"reason": "customer cancelled"})
    assert resp.status_code == 200
    assert resp.json()["current_status"] == "CANCELLED"
    # Row still exists.
    assert client.get(f"/shipments/{sid}", headers=staff).status_code == 200
    audit = client.get(f"/audit?entity_type=shipments&entity_id={sid}", headers=staff).json()
    assert any(a["action"] == "cancel" for a in audit["items"])


# ── stale_for_hours ──
def test_stale_for_hours_filter(client, staff, shipment):
    sid = shipment["id"]
    # Add a milestone 10 hours ago.
    old = datetime.now(timezone.utc) - timedelta(hours=10)
    _add(client, staff, sid, "PICKED_UP", event_at=old)

    stale = client.get("/shipments?stale_for_hours=6", headers=staff).json()
    assert any(s["id"] == sid for s in stale["items"])

    not_stale = client.get("/shipments?stale_for_hours=24", headers=staff).json()
    assert all(s["id"] != sid for s in not_stale["items"])


def test_timeline_returns_milestones_and_audit(client, staff, shipment):
    sid = shipment["id"]
    _add(client, staff, sid, "PICKED_UP")
    tl = client.get(f"/shipments/{sid}/timeline", headers=staff).json()
    assert len(tl["milestones"]) == 1
    assert isinstance(tl["audit"], list)


def test_has_data_quality_flags_filter(client, staff, shipment):
    sid = shipment["id"]
    _add(client, staff, sid, "DELIVERED")  # impossible → flag
    flagged = client.get("/shipments?has_data_quality_flags=true", headers=staff).json()
